func init() {
	for _, line := range rawData {
		parts := splitRaw(line)
		if len(parts) < 4 {
			continue
		}
		cat, name, em, kw := parts[0], parts[1], parts[2], parts[3]
		e := Emoji{
			Emoji:    em,
			Name:     name,
			Category: cat,
			Keywords: strings.Fields(kw),
		}
		List = append(List, e)
		code := name
		Shortcodes[code] = em
		ByEmoji[em] = code
	}
}

func splitRaw(line string) []string {
	var out []string
	start := 0
	for i := 0; i < len(line); i++ {
		if line[i] == '|' {
			out = append(out, line[start:i])
			start = i + 1
		}
	}
	out = append(out, line[start:])
	return out
}
